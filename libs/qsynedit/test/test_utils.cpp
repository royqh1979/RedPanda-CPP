#include "test_utils.h"
#include <QFontDatabase>
#include <QDebug>

TokenInfoList parseLine(QSynedit::Syntaxer *syntaxer, const QString &lineText)
{
    TokenInfoList result;
    syntaxer->resetState();
    syntaxer->setLine(0,lineText,0);
    while(!syntaxer->eol()) {
        PTokenInfo info = std::make_shared<TokenInfo>();
        info->token = syntaxer->getToken();
        info->attribute = syntaxer->getTokenAttribute();
        info->startChar = syntaxer->getTokenPos();
        info->state = syntaxer->getState();
        result.append(info);
        syntaxer->next();
    }
    return result;
}

QList<TokenInfoList> parseLines(QSynedit::Syntaxer *syntaxer, const QStringList &text)
{
    QList<TokenInfoList> result;
    syntaxer->resetState();
    for (int i=0;i<text.size();i++) {
        TokenInfoList list;
        syntaxer->setLine(i,text[i],i);
        while(!syntaxer->eol()) {
            PTokenInfo info = std::make_shared<TokenInfo>();
            info->token = syntaxer->getToken();
            info->attribute = syntaxer->getTokenAttribute();
            info->startChar = syntaxer->getTokenPos();
            info->state = syntaxer->getState();
            list.append(info);
            syntaxer->next();
        }
        result.append(list);
    }
    return result;
}


QStringList filterTokens(const QList<TokenInfoList> &infoList, const std::unordered_set<QSynedit::PTokenAttribute> &targetAttributes)
{
    QList<QString> result;
    for (int i=0;i<infoList.size();i++) {
        for (int j=0;j<infoList[i].size();j++) {
            if (targetAttributes.find(infoList[i][j]->attribute)!=targetAttributes.end())
                result.append(infoList[i][j]->token);
        }
    }
    return result;
}

QStringList filterTokens(const QList<TokenInfoList> &infoList, const QSynedit::PTokenAttribute &targetAttribute)
{
    QList<QString> result;
    for (int i=0;i<infoList.size();i++) {
        for (int j=0;j<infoList[i].size();j++) {
            if (targetAttribute == infoList[i][j]->attribute)
                result.append(infoList[i][j]->token);
        }
    }
    return result;
}

// The bundled test fonts (libs/qsynedit/test/fonts/, generated by
// gen_test_font.py) have fully deterministic metrics: half-width ASCII,
// full-width CJK/emoji, zero-width ZWJ/variation selectors. Use them
// instead of environment fonts so tests don't depend on the platform's
// font fallback.
static bool installTestFonts()
{
    static bool ok = [](){
        int mono = QFontDatabase::addApplicationFont("fonts/qsynedit-test-mono.ttf");
        int prop = QFontDatabase::addApplicationFont("fonts/qsynedit-test-prop.ttf");
        bool result = (mono >= 0 && prop >= 0);
        if (!result)
            qWarning() << "failed to install the bundled test fonts;"
                       << "tests that depend on font metrics will fail";
        return result;
    }();
    return ok;
}

QString defaultMonoFont()
{
    installTestFonts();
    return "QSynedit Test Mono";
}

QString testProportionalFont()
{
    installTestFonts();
    return "QSynedit Test Prop";
}
